CREATE TABLE cuentas (
    email VARCHAR(254) PRIMARY KEY,
    password_hash VARCHAR(100) NOT NULL,
    rol VARCHAR(20) NOT NULL CHECK (rol IN ('USER', 'ADMIN'))
);

CREATE TABLE torneos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    inicio DATE NOT NULL,
    fin DATE NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('BORRADOR', 'PROXIMO', 'ACTIVO', 'FINALIZADO')),
    regla VARCHAR(20) NOT NULL CHECK (regla IN ('CLASICA', 'ALTERNATIVA', 'FINAL_DOBLE')),
    CHECK (inicio <= fin)
);

CREATE TABLE equipos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id BIGINT NOT NULL REFERENCES torneos(id),
    nombre VARCHAR(100) NOT NULL,
    UNIQUE (id, torneo_id),
    UNIQUE (torneo_id, nombre)
);

CREATE TABLE partidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    torneo_id BIGINT NOT NULL REFERENCES torneos(id),
    local_id BIGINT NOT NULL,
    visitante_id BIGINT NOT NULL,
    inicio TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    cierre TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('PROXIMO', 'EN_JUEGO', 'SUSPENDIDO', 'FINALIZADO')),
    es_final BOOLEAN NOT NULL,
    resultado_local SMALLINT CHECK (resultado_local BETWEEN 0 AND 99),
    resultado_visitante SMALLINT CHECK (resultado_visitante BETWEEN 0 AND 99),
    UNIQUE (id, torneo_id),
    FOREIGN KEY (local_id, torneo_id) REFERENCES equipos(id, torneo_id),
    FOREIGN KEY (visitante_id, torneo_id) REFERENCES equipos(id, torneo_id),
    CHECK (local_id <> visitante_id),
    CHECK (cierre <= inicio),
    CHECK ((estado = 'FINALIZADO' AND resultado_local IS NOT NULL AND resultado_visitante IS NOT NULL)
        OR (estado <> 'FINALIZADO' AND resultado_local IS NULL AND resultado_visitante IS NULL))
);

CREATE TABLE inscripciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    torneo_id BIGINT NOT NULL REFERENCES torneos(id),
    email VARCHAR(254) NOT NULL REFERENCES cuentas(email),
    PRIMARY KEY (torneo_id, email)
);

CREATE TABLE predicciones (
    torneo_id BIGINT NOT NULL,
    partido_id BIGINT NOT NULL,
    email VARCHAR(254) NOT NULL,
    goles_local SMALLINT NOT NULL CHECK (goles_local BETWEEN 0 AND 99),
    goles_visitante SMALLINT NOT NULL CHECK (goles_visitante BETWEEN 0 AND 99),
    creada TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    actualizada TIMESTAMP(9) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (partido_id, email),
    FOREIGN KEY (partido_id, torneo_id) REFERENCES partidos(id, torneo_id),
    FOREIGN KEY (torneo_id, email) REFERENCES inscripciones(torneo_id, email),
    CHECK (creada <= actualizada)
);
